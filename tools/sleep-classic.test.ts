  const original = process.env.ANTHROPIC_API_KEY
  process.env.ANTHROPIC_API_KEY = 'test-key'
  const calls: any[] = []
  const fake: any = async (_url: string, opts: any) => { calls.push(JSON.parse(opts.body)); return new Response(JSON.stringify({ content: [{ type: 'text', text: JSON.stringify({ paragraphs: Array.from({ length: 5 }, () => '그들은 조용히 바다를 바라보며 아침을 기다렸습니다. '.repeat(8)) }) }] }), { status: 200 }) }
