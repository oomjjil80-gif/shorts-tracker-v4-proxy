// Zero-cost sleep classic pilot regression tests, no Anthropic/OpenAI/image/TTS calls.
import test from 'node:test'
import assert from 'node:assert/strict'
import { normalizeLongformBrief, sleepClassicAss, cardErrors } from '../lib/generative/longform.js'
import { thumbnailCopyErrors } from '../lib/generative/wisdomThumbnail.js'
import { isSleepClassic, SLEEP_CHAPTERS, SLEEP_CLASSIC_TITLE, sleepClassicOutline, splitSleepParagraphs, createSleepClassicPlanner, reviewSleepClassicStory, sleepChapterLength } from '../lib/generative/sleepClassic.js'

const TOPIC = '오디세이아 제9권 외눈박이 거인 폴리페모스'

test('sleep classic opt-in preserves legacy and refuses other profiles/presets', () => {
  const base = normalizeLongformBrief({ kind: 'topic', text: TOPIC, targetSeconds: 2700 }, 'wisdom_longform')
  assert.equal(base.sleepClassic, undefined)
  const sleep = normalizeLongformBrief({ kind: 'topic', text: TOPIC, targetSeconds: 2700, sleepClassic: 'odyssey-cyclops-v1', voiceProfile: 'male-middle' }, 'wisdom_longform')
  assert.ok(isSleepClassic(sleep))
  assert.equal(sleep.creative?.resolved.voiceProfile, 'male-middle')
  assert.throws(() => normalizeLongformBrief({ kind: 'topic', text: TOPIC, sleepClassic: 'odyssey-cyclops-v1' }, 'senior_longform'))
  assert.throws(() => normalizeLongformBrief({ kind: 'topic', text: TOPIC, sleepClassic: 'arbitrary' }, 'wisdom_longform'))
})
test('the published nine-chapter outline is deterministic and matches approved story order', () => {
  const o = sleepClassicOutline()
  assert.equal(o.title, SLEEP_CLASSIC_TITLE)
  assert.equal(o.sections.length, 9)
  assert.ok(o.sections[5].points.join(' ').includes('아무도 아니다'))
  assert.match(o.sections[8].points.join(' '), /포세이돈/)
  assert.equal(SLEEP_CHAPTERS.reduce((n, c) => n + c.chars, 0), 15300)
  assert.equal(sleepChapterLength(8), 2600)
  assert.deepEqual(sleepClassicOutline(), o)
  assert.deepEqual(thumbnailCopyErrors(o.thumbnail.lines, o.title), [], 'production PLAN outline thumbnail gate must PASS')
  assert.deepEqual(cardErrors(splitSleepParagraphs(['오디세이아 이야기를 시작합니다.'])[0]), [], 'narration card must pass existing PLAN validation')
})
test('Claude receives locked beats and no full screenplay generated by an unrelated GPT', async () => {
  const original = process.env.ANTHROPIC_API_KEY
  process.env.ANTHROPIC_API_KEY = 'test-key'
  const calls: any[] = []
  const fake: any = async (_url: string, opts: any) => { calls.push(JSON.parse(opts.body)); return new Response(JSON.stringify({ content: [{ type: 'text', text: JSON.stringify({ paragraphs: Array.from({ length: 5 }, () => '그들은 조용히 바다를 바라보며 아침을 기다렸습니다. '.repeat(6)) }) }] }), { status: 200 }) }
  try {
    const p = createSleepClassicPlanner(fake)
    const outline = await p.outline({} as any, 9, 'x')
    const d = await p.section({ brief: {} as any, outline, index: 1, previousTail: [], targetChars: 900 }, 'not-used')
    assert.ok(d.sentences.length > 0)
    assert.equal(calls.length, 1)
    assert.match(calls[0].messages[0].content, /로토파고이/)
    assert.equal(d.sentences[0].color, 'yellow')
    assert.ok(d.sentences.every((s) => [...s.say].length < 1200))
  } finally {
    if (original === undefined) delete process.env.ANTHROPIC_API_KEY; else process.env.ANTHROPIC_API_KEY = original
  }
})
test('sleep narration hides changing ASS cards while legacy ASS remains untouched', () => {
  assert.match(sleepClassicAss(), /\[Events\]/)
  assert.doesNotMatch(sleepClassicAss(), /Dialogue:/)
  assert.equal(splitSleepParagraphs(['한 문장입니다. 다음 문장입니다.'])[0].show[0], '조용한 고전')
})
test('GPT quality gate rejects a false approval with concrete issues', async () => {
  const fake: any = async (_url: string, opts: any) => {
    const p = JSON.parse(opts.body)
    assert.match(p.instructions, /independent Korean audiobook/)
    return new Response(JSON.stringify({ output_text: JSON.stringify({ approved: true, fidelity: 2, standalone: 4, bedtime: 5, story: 4, originality: 4, issues: ['부하 희생자 수 불일치'] }) }), { status: 200 })
  }
  const result = await reviewSleepClassicStory([{ id: 's1', sentences: splitSleepParagraphs(['아무도 아니다.']) }], 'test', fake)
  assert.equal(result.approved, false)
  assert.equal(result.issues.length, 1)
})
