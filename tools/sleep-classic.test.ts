const TOPIC = '오디세이아 제9권 외눈박이 거인 폴리페모스'

test('sleep classic opt-in preserves legacy and refuses other profiles/presets', () => {
  const base = normalizeLongformBrief({ kind: 'topic', text: TOPIC, targetSeconds: 2700 }, 'wisdom_longform')
  assert.equal(base.sleepClassic, undefined)
  const sleep = normalizeLongformBrief({ kind: 'topic', text: TOPIC, targetSeconds: 2700, sleepClassic: 'odyssey-cyclops-v1', voiceProfile: 'male-middle' }, 'wisdom_longform')
  assert.ok(isSleepClassic(sleep))
  assert.equal(sleep.creative?.resolved.voiceProfile, 'male-middle')
  assert.throws(() => normalizeLongformBrief({ kind: 'topic', text: TOPIC, sleepClassic: 'odyssey-cyclops-v1' }, 'senior_longform'))
  assert.throws(() => normalizeLongformBrief({ kind: 'topic', text: TOPIC, sleepClassic: 'arbitrary' }, 'wisdom_longform'))
})
