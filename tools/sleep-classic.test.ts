    assert.equal(calls[0].max_tokens, 7000)
    assert.equal(Object.hasOwn(calls[0], 'temperature'), false, 'Claude Sonnet 5 rejects non-default temperature with HTTP 400')
    assert.equal(Object.hasOwn(calls[0], 'top_p'), false)
    assert.equal(Object.hasOwn(calls[0], 'top_k'), false)
    assert.match(calls[0].messages[0].content, /로토파고이/)
    assert.equal(d.sentences[0].color, 'yellow')
    assert.ok(d.sentences.every((s) => [...s.say].length < 1200))
